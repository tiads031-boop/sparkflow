import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from '../web/node_modules/typescript/lib/typescript.js';
import ical from '../api/node_modules/node-ical/node-ical.js';
const source = readFileSync(new URL('../web/src/utils/courseSchedule.ts', import.meta.url), 'utf8');
const js = ts.transpile(source, { target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.ESNext });
const { scheduleIcs, occurrences, localDay } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const title = '中文课程，含分号;逗号,反斜线\\与换行\n' + '长标题'.repeat(30);
const backup = { exportedAt: '2026-09-01T00:00:00Z', courses: [{ id: 'c', semesterId: 's', teacher: '张老师', room: 'A101', events: [{ id: 'e', title, startTime: '2026-09-07T08:00:00+08:00', endTime: '2026-09-07T09:40:00+08:00', isOverride: true, location: 'B202' }] }] };
const output = scheduleIcs(backup);
assert.ok(output.split('\r\n').every(line => Buffer.byteLength(line) <= 75), 'ICS lines must fit 75 UTF-8 bytes');
const event = Object.values(ical.sync.parseICS(output)).find(x => x.type === 'VEVENT');
assert.equal(event.summary, title);
assert.equal(event.location, 'B202');
assert.equal(event.start.toISOString(), '2026-09-07T00:00:00.000Z');
assert.equal(occurrences(backup, 'other').length, 0);
assert.equal(occurrences(backup, 's')[0].isOverride, true);
assert.equal(localDay(new Date(2026, 8, 7, 0, 1)), '2026-09-07');
console.log('PASS: ICS round trip, UTF-8 folding, adjusted location, timezone, semester isolation, local dates');
